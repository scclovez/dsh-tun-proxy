import { publicSettings } from './core/settings.js'

export async function dispatch(service, action, body = {}) {
  switch (action) {
    case 'status': return service.status({ verbose: body.verbose === true })
    case 'ipCheck': return service.ipCheck()
    case 'start': return service.start({ onProgress: () => {} })
    case 'stop': return service.stop()
    case 'restart': return service.restart()
    case 'validate': { const result = await service.compile(); return { valid: true, source: result.base.source } }
    case 'install': return service.install({ version: body.version ?? '', force: body.force === true, sha256: body.sha256 ?? '', onProgress: () => {} })
    case 'refresh': return service.updateSubscription()
    case 'import': return service.importSource({ source: body.source })
    case 'clearSubscription': return publicSettings(service.updateSettings({ subscriptionUrl: '' }))
    case 'logs': return service.logs({ lines: Math.min(500, Math.max(1, Number(body.lines) || 120)) })
    case 'settings': return publicSettings(service.readSettings())
    case 'profiles': return service.profileList()
    case 'addProfile': return service.addProfile({ source: body.source, name: body.name })
    case 'activateProfile': return service.activateProfile(body.id)
    case 'removeProfile': return service.removeProfile(body.id)
    case 'refreshProfile': return service.refreshProfile(body.id)
    case 'editProfile': return service.editProfile(body.profile)
    case 'profileContent': return service.profileContent(body.id)
    case 'syncProfiles': return service.syncProfiles()
    case 'activity': return service.activity()
    case 'closeConnections': return service.closeConnections(body.id)
    case 'rules': return service.rules()
    case 'batchDelay': return service.batchDelay(body.nodes)
    case 'exportBackup': return service.exportBackup()
    case 'restoreBackup': return service.restoreBackup(body.backup)
    case 'set': return publicSettings(service.updateSettings(body.patch ?? {}))
    case 'catalog': return service.catalog({ refresh: body.refresh === true })
    case 'upsertProxy': return service.upsertProxy(body.proxy)
    case 'removeProxy': return service.removeProxy(body.name)
    case 'nodes': return service.nodes()
    case 'select': return service.selectNode({ group: body.group, node: body.node ?? '' })
    case 'delay': return service.delay({ node: body.node })
    case 'mode': return service.setMode({ mode: body.mode })
    case 'uninstall': return service.uninstall({ purge: body.purge === true })
    default: throw Object.assign(new Error(`未知 action：${action}`), { code: 'bad-action' })
  }
}
